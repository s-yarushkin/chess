export function coachingFor(p){
 const stage=stages[p.category]||stages.mate1;
 const tags=new Set(String(p.theme||'').split(/\s+/));
 const motif=MOTIFS.find(m=>tags.has(m[0]));
 return {title:stage.title,prompt:stage.prompt,method:stage.method,focus:motif?motif[1]:stage.title,reflection:motif?motif[2]:'Объясни, какая фигура давала шах, какие поля короля были под контролем и почему не нашлось защиты.'};
}
